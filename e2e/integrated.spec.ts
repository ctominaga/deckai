import { test, expect } from "@playwright/test";

test("official navigation and complete Mock workflow with edit, cancel and reapproval", async ({page}) => {
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.goto("/");
  await expect(page.getByRole("heading",{name:"Visão geral"})).toBeVisible();
  await page.getByRole("link",{name:"Gerar com IA",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Gerar com IA",exact:true})).toBeVisible();
  await expect(page.locator(".official-side")).toHaveCSS("background-color","rgb(23, 23, 23)");
  await page.locator("#tab-briefing").click();
  await page.locator("#provider").selectOption("mock");
  await page.locator("#generate-script-button").click();
  await expect(page.locator("#script-status")).toHaveText("Rascunho");
  await page.getByRole("button",{name:"Editar título",exact:true}).click();
  await page.locator('[data-edit-field="scriptTitle"]').fill("Título cancelado");
  await page.getByRole("button",{name:"Cancelar",exact:true}).click();
  await expect(page.locator(".script-title")).not.toHaveText("Título cancelado");
  await page.getByRole("button",{name:"Editar título",exact:true}).click();
  await page.locator('[data-edit-field="scriptTitle"]').fill("Minha apresentação revisada");
  await page.getByRole("button",{name:"Salvar alterações",exact:true}).click();
  await expect(page.locator(".script-summary")).toContainText("Revisão 2");
  await expect(page.locator("#generate-presentation-button")).toBeDisabled();
  await page.locator("#approve-button").click();
  await expect(page.locator("#script-status")).toHaveText("Aprovado");
  await page.locator("#generate-presentation-button").click();
  await expect(page.locator(".slide-card")).toHaveCount(6);
  await expect(page.locator("#presentation-content .layout-tag")).toHaveText(["Capa","Texto + imagem","Duas colunas","Indicadores","Case","Encerramento"]);
  await page.screenshot({path:"test-results/integrated-desktop.png"});
  await page.locator(".advanced-json > summary").click();
  await page.locator("#shared-json-button").click();
  await expect(page.locator("#shared-json-output")).toContainText('"schemaVersion": "1.0"');
  await page.locator("#tab-script").click();
  await page.getByRole("button",{name:"Editar título",exact:true}).click();
  await page.locator('[data-edit-field="scriptTitle"]').fill("Reaprovação necessária");
  await page.getByRole("button",{name:"Salvar alterações",exact:true}).click();
  await expect(page.locator("#script-status")).toHaveText("Rascunho");
  await expect(page.locator("#shared-json-output")).toBeHidden();
  await expect(page.locator("#generate-presentation-button")).toBeDisabled();
  await page.locator("#approve-button").click();
  await page.locator("#generate-presentation-button").click();
  await expect(page.locator(".slide-card")).toHaveCount(6);
  await page.locator("#shared-json-button").click();
  await expect(page.locator("#shared-json-output")).toBeVisible();
  await page.locator("#tab-briefing").click();
  await page.locator("#generate-script-button").click();
  await expect(page.locator("#shared-json-output")).toBeHidden();
  await expect(page.locator("#script-status")).toHaveText("Rascunho");
  await page.getByRole("link",{name:"Visão geral",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Visão geral"})).toBeVisible();
  expect(errors).toEqual([]);
});

test("Dev 3 local presentations, content approval and export simulations persist", async ({page}) => {
  await page.goto("/prototipo.html#presentations");
  await page.locator("#presentationTitle").fill("Apresentação local preservada");
  await page.locator("#presentationText").fill("Conteúdo demonstrativo");
  await page.getByRole("button",{name:"Salvar apresentação",exact:true}).click();
  await expect(page.locator("#presentationList")).toContainText("Apresentação local preservada");
  await page.getByRole("button",{name:"Biblioteca Jump",exact:true}).click();
  await page.locator("#jumpTitle").fill("Fonte simulada");
  await page.locator("#jumpBody").fill("Conteúdo fictício sem integração à IA");
  await page.locator("#jumpSource").fill("https://example.com/fonte-simulada");
  await page.getByRole("button",{name:"Criar rascunho",exact:true}).click();
  await page.getByRole("button",{name:"Enviar",exact:true}).click();
  await page.getByRole("button",{name:"Aprovar",exact:true}).click();
  await expect(page.locator("#jumpList .status")).toHaveText("approved");
  await page.getByRole("button",{name:"Exportações",exact:true}).click();
  await page.getByRole("button",{name:"Criar job",exact:true}).click();
  await page.getByRole("button",{name:"Criar job",exact:true}).click();
  await expect(page.locator("#jobList .item")).toHaveCount(1);
  await page.reload();
  await page.getByRole("button",{name:"Apresentações",exact:true}).click();
  await expect(page.locator("#presentationList")).toContainText("Apresentação local preservada");
  await page.getByRole("link",{name:"Gerar com IA",exact:true}).click();
  await page.getByRole("link",{name:"Apresentações",exact:true}).click();
  await expect(page.locator("#presentations")).toBeVisible();
});

test("AI navigation remains usable on mobile and sends no automatic generation", async ({page}) => {
  await page.setViewportSize({width:390,height:844});
  const posts: string[] = [];
  page.on("request",req => { if(req.method()==="POST")posts.push(req.url()); });
  await page.goto("/gerar-ia.html");
  await page.locator("#toggle-site-nav").click();
  await expect(page.getByRole("link",{name:"Visão geral",exact:true})).toBeVisible();
  await page.locator("#tab-briefing").click();
  await expect(page.locator("#briefing-form")).toBeVisible();
  await page.locator("#provider").selectOption("gemini");
  expect(posts.filter(url => !url.endsWith("/api/briefing/invalidate"))).toEqual([]);
  await expect(page.locator("#mode-badge")).toHaveText("Gemini · IA real");
  await page.screenshot({path:"test-results/integrated-mobile.png"});
});
